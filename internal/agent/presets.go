// presetByKey 按 key 查找内置预设（未命中返回 nil）。
func presetByKey(key string) *PromptPreset {
	for i := range BuiltinPresets {
		if BuiltinPresets[i].Key == key {
			return &BuiltinPresets[i]
		}
	}
	return nil
}

// ResolveMainPrompt 解析本回合生效的 Narrator 系统提示词。
//
// 优先级：Style.CustomPrompt（自定义）> Style.PromptPreset（预设）> default 预设。
// 结果 = 提示词正文 + 技术契约段；playerName 用于替换 {{player}} 占位符
// （空则用"玩家"）。
func ResolveMainPrompt(style *world.StyleConfig, playerName string) string {
	content := BuiltinPresets[0].Content // default
	if style != nil {
		if custom := strings.TrimSpace(style.CustomPrompt); custom != "" {
			content = custom
		} else if p := presetByKey(style.PromptPreset); p != nil {
			content = p.Content
		}
	}
	if strings.TrimSpace(playerName) == "" {
		playerName = "玩家"
	}
	content = strings.ReplaceAll(content, playerPlaceholder, playerName)
	return content + "\n\n" + narratorTechnicalContract
}
